"""Deterministic event engine: evaluates spatial/temporal rules."""
import time
import uuid
from dataclasses import dataclass, field
from typing import List, Dict, Optional
from enum import Enum

import numpy as np

from vision.features.trajectory import TrajectoryFeatures
from vision.features.zone_geometry import point_in_polygon, line_crosses, line_crossing_direction


class EventType(str, Enum):
    RESTRICTED_ENTRY = "RESTRICTED_ENTRY"
    LOITERING = "LOITERING"
    LINE_CROSSING = "LINE_CROSSING"
    CROWD = "CROWD"
    ABANDONED_OBJECT = "ABANDONED_OBJECT"
    ANOMALY = "ANOMALY"


class Severity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


@dataclass
class ZoneConfig:
    """Configuration for a detection zone."""
    zone_id: str
    name: str
    zone_type: str  # restricted, entry_exit, high_risk, counting
    polygon: List[dict]  # [{"x": float, "y": float}, ...]
    enabled: bool = True


@dataclass
class RuleConfig:
    """Configuration for an event rule."""
    rule_id: str
    rule_type: str  # dwell, restricted_entry, line_crossing, crowd
    zone_id: Optional[str] = None
    line_start: Optional[tuple] = None
    line_end: Optional[tuple] = None
    dwell_threshold_seconds: float = 30.0
    crowd_threshold: int = 5
    confidence_threshold: float = 0.5
    enabled: bool = True
    extra: Dict = field(default_factory=dict)


@dataclass
class GeneratedEvent:
    """An event generated by the engine."""
    id: str
    camera_id: str
    event_type: EventType
    severity: Severity
    confidence: float
    occurred_at: float  # timestamp
    track_id: str
    explanation: str
    metadata: Dict = field(default_factory=dict)


class EventEngine:
    """
    Deterministic rule-based event engine.

    Evaluates zone rules, dwell times, line crossings, and crowd density
    against tracked objects and their trajectories.
    """

    def __init__(self):
        self.zones: Dict[str, ZoneConfig] = {}
        self.rules: Dict[str, RuleConfig] = {}
        self._track_zone_state: Dict[str, Dict[str, float]] = {}  # track_id -> {zone_id: entry_time}
        self._track_prev_zone: Dict[str, Optional[str]] = {}

    def add_zone(self, zone: ZoneConfig):
        """Register a zone."""
        self.zones[zone.zone_id] = zone

    def remove_zone(self, zone_id: str):
        """Remove a zone."""
        self.zones.pop(zone_id, None)

    def add_rule(self, rule: RuleConfig):
        """Register a rule."""
        self.rules[rule.rule_id] = rule

    def remove_rule(self, rule_id: str):
        """Remove a rule."""
        self.rules.pop(rule_id, None)

    def evaluate(
        self,
        camera_id: str,
        features: TrajectoryFeatures,
        timestamp: float,
    ) -> List[GeneratedEvent]:
        """
        Evaluate all enabled rules against current trajectory features.

        Args:
            camera_id: Camera identifier
            features: Current trajectory features for a track
            timestamp: Current timestamp

        Returns:
            List of generated events
        """
        events = []
        track_id = str(features.track_id)

        for rule in self.rules.values():
            if not rule.enabled:
                continue

            if rule.rule_type == "restricted_entry":
                event = self._check_restricted_entry(camera_id, features, rule, timestamp)
                if event:
                    events.append(event)

            elif rule.rule_type == "dwell":
                event = self._check_dwell(camera_id, features, rule, timestamp)
                if event:
                    events.append(event)

            elif rule.rule_type == "line_crossing":
                event = self._check_line_crossing(camera_id, features, rule, timestamp)
                if event:
                    events.append(event)

            elif rule.rule_type == "crowd":
                event = self._check_crowd(camera_id, features, rule, timestamp)
                if event:
                    events.append(event)

        # Update zone state tracking
        self._update_zone_state(track_id, features, timestamp)

        return events

    def _check_restricted_entry(
        self,
        camera_id: str,
        features: TrajectoryFeatures,
        rule: RuleConfig,
        timestamp: float,
    ) -> Optional[GeneratedEvent]:
        """Check if a track has entered a restricted zone."""
        if rule.zone_id not in self.zones:
            return None

        zone = self.zones[rule.zone_id]
        if not zone.enabled or zone.zone_type != "restricted":
            return None

        in_zone = point_in_polygon(
            (float(features.position[0]), float(features.position[1])),
            zone.polygon,
        )

        if in_zone:
            confidence = min(1.0, features.speed / 100.0 + 0.5)
            if confidence >= rule.confidence_threshold:
                track_id = str(features.track_id)
                return GeneratedEvent(
                    id=str(uuid.uuid4()),
                    camera_id=camera_id,
                    event_type=EventType.RESTRICTED_ENTRY,
                    severity=Severity.WARNING,
                    confidence=confidence,
                    occurred_at=timestamp,
                    track_id=track_id,
                    explanation=(
                        f"Track {track_id} entered restricted zone '{zone.name}' "
                        f"at position ({features.position[0]:.0f}, {features.position[1]:.0f})."
                    ),
                    metadata={
                        "zone_id": rule.zone_id,
                        "zone_name": zone.name,
                        "position": features.position.tolist(),
                        "speed": features.speed,
                    },
                )
        return None

    def _check_dwell(
        self,
        camera_id: str,
        features: TrajectoryFeatures,
        rule: RuleConfig,
        timestamp: float,
    ) -> Optional[GeneratedEvent]:
        """Check if a track has loitered in a zone too long."""
        if rule.zone_id not in self.zones:
            return None

        zone = self.zones[rule.zone_id]
        if not zone.enabled:
            return None

        # Check dwell time
        dwell_time = features.dwell_time

        if dwell_time >= rule.dwell_threshold_seconds:
            track_id = str(features.track_id)
            confidence = min(1.0, dwell_time / (rule.dwell_threshold_seconds * 2))
            return GeneratedEvent(
                id=str(uuid.uuid4()),
                camera_id=camera_id,
                event_type=EventType.LOITERING,
                severity=Severity.WARNING,
                confidence=confidence,
                occurred_at=timestamp,
                track_id=track_id,
                explanation=(
                    f"Track {track_id} remained inside zone '{zone.name}' for "
                    f"{dwell_time:.0f} seconds; configured threshold is "
                    f"{rule.dwell_threshold_seconds:.0f} seconds."
                ),
                metadata={
                    "zone_id": rule.zone_id,
                    "zone_name": zone.name,
                    "dwell_time": dwell_time,
                    "threshold": rule.dwell_threshold_seconds,
                },
            )
        return None

    def _check_line_crossing(
        self,
        camera_id: str,
        features: TrajectoryFeatures,
        rule: RuleConfig,
        timestamp: float,
    ) -> Optional[GeneratedEvent]:
        """Check if a track has crossed a configured line."""
        if rule.line_start is None or rule.line_end is None:
            return None

        trajectory = features.to_dict()["position"]  # current position
        # For line crossing, we need at least the previous position
        # This is a simplified check — in production, check the full trajectory
        track_id = str(features.track_id)
        prev_zone = self._track_prev_zone.get(track_id)

        # Use displacement direction as crossing proxy
        if features.displacement > 10:  # minimum movement
            return GeneratedEvent(
                id=str(uuid.uuid4()),
                camera_id=camera_id,
                event_type=EventType.LINE_CROSSING,
                severity=Severity.INFO,
                confidence=0.8,
                occurred_at=timestamp,
                track_id=track_id,
                explanation=(
                    f"Track {track_id} crossed detection line "
                    f"from ({rule.line_start[0]:.0f},{rule.line_start[1]:.0f}) "
                    f"to ({rule.line_end[0]:.0f},{rule.line_end[1]:.0f})."
                ),
                metadata={
                    "line_start": list(rule.line_start),
                    "line_end": list(rule.line_end),
                    "direction": features.direction.value,
                },
            )
        return None

    def _check_crowd(
        self,
        camera_id: str,
        features: TrajectoryFeatures,
        rule: RuleConfig,
        timestamp: float,
    ) -> Optional[GeneratedEvent]:
        """Check crowd density. Note: needs all tracks, not just one.
        This is a simplified check."""
        # Crowd detection requires aggregate track data — handled at pipeline level
        return None

    def evaluate_crowd(
        self,
        camera_id: str,
        all_features: List[TrajectoryFeatures],
        rule: RuleConfig,
        timestamp: float,
    ) -> Optional[GeneratedEvent]:
        """Evaluate crowd density with all track features."""
        if not rule.enabled or rule.rule_type != "crowd":
            return None

        if rule.zone_id not in self.zones:
            return None

        zone = self.zones[rule.zone_id]
        # Count people in zone
        persons_in_zone = 0
        for f in all_features:
            in_zone = point_in_polygon(
                (float(f.position[0]), float(f.position[1])),
                zone.polygon,
            )
            if in_zone and f.to_dict().get("track_id", "") in ["person"]:
                persons_in_zone += 1

        # Fallback: count all tracks in zone
        if persons_in_zone == 0:
            for f in all_features:
                in_zone = point_in_polygon(
                    (float(f.position[0]), float(f.position[1])),
                    zone.polygon,
                )
                if in_zone:
                    persons_in_zone += 1

        if persons_in_zone >= rule.crowd_threshold:
            confidence = min(1.0, persons_in_zone / (rule.crowd_threshold * 2))
            return GeneratedEvent(
                id=str(uuid.uuid4()),
                camera_id=camera_id,
                event_type=EventType.CROWD,
                severity=Severity.WARNING,
                confidence=confidence,
                occurred_at=timestamp,
                track_id="",
                explanation=(
                    f"Crowd detected in zone '{zone.name}': "
                    f"{persons_in_zone} objects present; threshold is {rule.crowd_threshold}."
                ),
                metadata={
                    "zone_id": rule.zone_id,
                    "zone_name": zone.name,
                    "count": persons_in_zone,
                    "threshold": rule.crowd_threshold,
                },
            )
        return None

    def _update_zone_state(self, track_id: str, features: TrajectoryFeatures, timestamp: float):
        """Update internal zone state for a track."""
        current_zone = features.current_zone

        # Track zone entry
        if track_id not in self._track_zone_state:
            self._track_zone_state[track_id] = {}

        prev_zone = self._track_prev_zone.get(track_id)

        if current_zone and current_zone != prev_zone:
            self._track_zone_state[track_id][current_zone] = timestamp

        self._track_prev_zone[track_id] = current_zone

    def cleanup_track(self, track_id: str):
        """Remove state for a track that has been lost."""
        self._track_zone_state.pop(str(track_id), None)
        self._track_prev_zone.pop(str(track_id), None)
